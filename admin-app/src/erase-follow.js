// ما بقي على المدير بعد الحذف (participantDelete): تأكيد لم يصل يُرسل بنفسه إلى العنوان المعاد (حُذف من كل مكان بعدها)،
// وملفات باقية في المخزن تُحذف من مجلدها قبل التأكيد، وطلب لم يُغلق، وسطر سجل لم يُكتب. null: لا شيء بقي
export function deleteFollowUp(r) {
  if (!r?.success) return null;
  const todo = [];
  if (r.files_failed) todo.push(`تعذّر حذف ملفاته من المخزن، وهي باقية تحت المجلد ${r.folder || ''}. احذفها منه، ثم أرسل له التأكيد بنفسك.`);
  if (!r.mailed && r.email) todo.push(`لم يصله تأكيد تنفيذ الحذف. أرسله بنفسك إلى ${r.email} بعنوان «نُفّذ طلب حذف بياناتك»، فهذا العنوان لا يبقى في المنصة بعد إغلاق هذه النافذة.`);
  if (r.request_open) todo.push('طلب الحذف لم يُغلق في السجل لعطل عابر، ووصلك تنبيه برقمه.');
  if (r.audit_failed) todo.push('لم يُكتب سطر الحذف في سجل التدقيق، ووصلك تنبيه.');
  return todo.length ? `حُذف المشارك، وبقي عليك: ${todo.join(' ')}` : null;
}
