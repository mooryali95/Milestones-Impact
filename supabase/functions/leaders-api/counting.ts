// علامتان على جدول المشاركين:
//   is_demo  حساب العرض التوضيحي: خارج كل قائمة ورقم وبريد وشهادة، ولا يُربط بجهة (قيد participants_demo_no_org).
//   is_test  حساب اختبار داخلي (قرار المالك 2026-11-11): خارج الأرقام وحدها، وحساب عادي في القوائم التشغيلية بشارته.
// القواعد المسماة هنا وحدها تجيب، ولا يُكتب الشرط باليد في استعلام. الحارس counting_guard_test.ts يقرأ ملفات الخادم،
// ويُسقط البناء إن قرأ استعلام صفوفًا من المشاركين أو من جداول العد (القياسات، الحضور، الشهادات) بلا قاعدة منها ولا
// استثناء مكتوب بسببه على سطره أو السطر الذي قبله: «// counting-exempt: السبب».
//
// col: اسم الجدول المضمَّن حين يُصفّى من جدول آخر (participants!inner)، مثل listed(q, 'participants').
// المرشح على جدول مضمَّن لا يحذف الصف الأب إلا مع !inner، فمن يستعمل col يضمّن بـ!inner.

type Flags = { is_demo?: boolean | null; is_test?: boolean | null } | null | undefined;
const at = (col: string, k: string) => (col ? `${col}.${k}` : k);

/** يظهر في القوائم التشغيلية (المشاركون، المراجعات، السجلات): كل حساب إلا حساب العرض */
export const listed = (q: any, col = '') => q.eq(at(col, 'is_demo'), false);
/** يدخل الأرقام والتقارير والقياس: لا حساب العرض ولا حساب الاختبار */
export const counted = (q: any, col = '') => q.eq(at(col, 'is_demo'), false).eq(at(col, 'is_test'), false);

/** القاعدتان نفساهما لصف مقروء */
export const isListed = (p: Flags) => !p?.is_demo;
export const isCounted = (p: Flags) => !p?.is_demo && !p?.is_test;

// ما يخرج بسبب حساب العرض إلى طرف ثالث (راعي المبادرة، مؤكد الأثر) أو يثبت أثرًا رسميًا (حضور، شهادة) يُحاكى:
// يرى صاحب الحساب التجربة كاملة، ولا يُكتب الأثر ولا يخرج البريد. الأفعال المغلقة عليه كليًا في DEMO_BLOCKED (index.ts)
export const simulated = (p: Flags) => !!p?.is_demo;
