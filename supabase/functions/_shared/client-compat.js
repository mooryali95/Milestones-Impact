// المصدر الواحد يستورده العميل (src/lib/api.js يرسل CLIENT_LEVEL في الرابط بمعامل cl) والخادم (leaders-api يرد
// update_required لمن هو أقل من MIN_CLIENT_LEVEL). بصمة البناء (index-<hash>.js) لا ترتيب لها فلا تصلح حدًا أدنى، والرقم هنا
// يتقدم يدويًا في الإيداع نفسه الذي يكسر التوافق، فيبقى الناتج المبني مطابقًا لمصدره (لا SHA ولا وقت بناء).
// المعامل في الرابط لا في ترويسة: الترويسة غير المألوفة تحتاج إذن CORS قبل أن تُرسل (المرحلة 4)، والمعامل يصل من أول طلب.
//
// القاعدة (ش4): التغيير المتوافق للخلف (وهو الأصل: توسيع ثم انكماش) لا يمس هذا الملف. وحين يُحذف فعل أو حقل يعتمد عليه
// إصدار سابق بعد مدة الاحتفاظ (14 يومًا)، أو يتغير شكل رد لا يفهمه العميل القديم: يزيد CLIENT_LEVEL ويصير MIN_CLIENT_LEVEL
// مساويًا له في الإيداع نفسه. العميل بلا مستوى (أقدم من هذه المرحلة) يُخدم كما كان: لا يُعرف عمره، وصفحته لا تفهم الرد.

export const CLIENT_LEVEL = 1;
export const MIN_CLIENT_LEVEL = 1;
export const LEVEL_PARAM = 'cl';

// أفعال تُخدم لأي عميل مهما قدم: الرصد من جهة العميل (يجب أن يصل ليُعرف ما أصاب العميل القديم)
export const ANY_LEVEL = new Set(['client.event']);

/** مستوى العميل من رابط الطلب، أو null إن غاب أو لم يكن عددًا صحيحًا صغيرًا (0 مستوى صالح: أقل من أي حد أدنى) */
export function clientLevelOf(url) {
  try {
    const v = new URL(String(url)).searchParams.get(LEVEL_PARAM);
    if (v == null || !/^\d{1,4}$/.test(v)) return null;
    return Number(v);
  } catch { return null; }
}

/** هل يُرد update_required؟ مستوى معروف أقل من الحد الأدنى، لفعل غير معفى */
export function needsUpdate(level, action, min = MIN_CLIENT_LEVEL) {
  if (level == null || ANY_LEVEL.has(String(action || ''))) return false;
  return level < min;
}
