## مسرد المصطلحات
- **المخرج** (Output): ما ينتجه المشروع مباشرة.
- **النتيجة** (Outcome): التغير في السلوك أو الاستخدام بعد تبني المخرج.
- **المنفعة** (Benefit): تحسن مقيس له مالك ومؤشر وتاريخ تحقق.
- **المنفعة السلبية** (Dis-benefit): نتيجة يراها طرف سلبية، وتنتج عن التغيير نفسه.
- **الأثر** (Impact): التحول الأوسع طويل المدى.
- **مالك المنفعة** (Benefit Owner): من يتسلم المنفعة ويُحاسب على تحققها.
- **مالك تغيير الأعمال** (Business Change Manager): من يقود التبني في وحدات الأعمال.
- **ملف المنفعة** (Benefit Profile): صفحة تعرّف المنفعة وقياسها ومخاطرها.
- **سجل المنافع** (Benefits Register): القائمة الحية للمنافع ومؤشراتها وملاكها.
- **خطة تحقيق المنافع** (Benefits Realization Plan): معالم قراءة المنافع ومسؤولياتها.
- **نظرية التغيير** (Theory of Change): خريطة سببية تشرح لماذا سيحدث التغيير.
- **الإطار المنطقي** (Logical Framework): مصفوفة الأهداف والمؤشرات ووسائل التحقق والافتراضات.
- **الإسناد** (Attribution): نسبة التغيير إلى التدخل وحده.
