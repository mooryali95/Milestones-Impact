## جدارات القائد في إطار المعلم
**ما يملكه القائد ذاتيًا**:
- التفكير القراري: يرى في كل معلم سؤالًا يحتاج قرارًا، لا تاريخًا يُعبر.
- قراءة الانحراف: يلتقط الانحراف عن خط الأساس واتجاه المعالم مبكرًا.
- الحكم على الاستمرار: يسأل عند كل بوابة: هل ما زال المشروع يستحق الاستثمار؟

**ما يقدمه للمؤسسة**:
- تصميم منظومة المعالم: سجل متوازن بأنواعه الأربعة، ولكل معلم صاحب قرار.
- حوكمة البوابات: جلسات قرار منضبطة بمعايير معلنة.
- بيانات موثوقة: تقارير تخدم القرار لا الرواية.

> كل معلم اختبار عملي لهذه الجدارات: سؤال، ثم قراءة، ثم قرار موثق. أما جدارات قيادة الأشخاص، كالاستجابة المنضبطة وانتقال العهدة، فمكانها الإطار الثالث.

