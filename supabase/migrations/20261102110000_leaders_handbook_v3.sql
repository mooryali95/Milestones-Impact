## مسرد المصطلحات
- **الجدارة** (Competency): قدرة مثبتة بالسلوك تجمع المعرفة والمهارة والاتجاه.
- **نموذج المدى الكامل** (Full Range Leadership): إطار يجمع القيادة التحويلية والتبادلية (الباب الأول).
- **القيادة التحويلية** (Transformational Leadership): إلهام واستثارة فكرية واهتمام بكل فرد.
- **القيادة التبادلية** (Transactional Leadership): توقعات واضحة ومكافأة عادلة للإنجاز.
- **القيادة المشتركة** (Shared Leadership): توزيع أدوار القيادة على الفريق بحسب الخبرة.
- **علاقة القائد بالعضو** (Leader Member Exchange, LMX): جودة العلاقة الفردية بين القائد وكل عضو.
- **الأمان النفسي** (Psychological Safety): ثقة الفريق بأن رفع المشكلة أو الخطأ لن يُعاقب.
- **التوجيه والمواءمة والالتزام** (Direction, Alignment, Commitment): نتائج القيادة في الجماعة وفق إطار CCL.
- **قصد القائد** (Commander's Intent): الغاية من التوجيه، لا كلماته.
- **القيادة الموقفية** (Situational Leadership): تكييف الأسلوب مع خبرة الفرد بالمهمة واستعداده لها.
