## مسرد المصطلحات
- **المعلم** (Milestone): نقطة قرار وتحكم مدتها صفر.
- **بوابة المرحلة** (Stage Gate): معلم إلزامي لا يُعبر إلا بقرار رسمي.
- **خط الأساس** (Baseline): الخطة المعتمدة التي يُقاس الانحراف عنها.
- **الانزلاق** (Slippage): تأخر موعد المعلم المتوقع عن تاريخه في خط الأساس.
- **مبرر الاستمرار** (Business Justification): سبب استحقاق المشروع للاستثمار، يُراجع عند كل مرحلة.
- **المسار الحرج** (Critical Path): أطول سلسلة أنشطة مترابطة، وتحدد موعد الانتهاء.
- **الفائض الزمني** (Float): التأخير الذي يحتمله نشاط دون أن يمس الموعد.
- **طلب التغيير** (Change Request): طلب موثق لتعديل نطاق أو موعد أو تكلفة معتمدة.
- **حدود التحمل** (Tolerance): هامش الانحراف المسموح قبل التصعيد.
- **تحليل اتجاه المعالم** (Milestone Trend Analysis): تتبع التواريخ المتوقعة للمعالم عبر الزمن.
- **القيمة المكتسبة** (Earned Value): قيمة ما أُنجز فعلًا بسعر الخطة.
