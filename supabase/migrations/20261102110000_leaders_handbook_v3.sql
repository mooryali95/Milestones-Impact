## قيادة القادة
حين يصبح من تقودهم مديري مشاريع وقادة فرق، يتغير عملك من القيادة المباشرة إلى بناء القادة:
- **من الحل إلى السؤال**: تعيد المشكلة إلى صاحبها بسؤال يبني حكمه، ولا تحلها عنه.
- **من متابعة الخطوات إلى المعايير**: تتفق معهم على ما يعنيه «جيد» وحدود التصعيد، ثم تتابع النتائج لا الخطوات.
- **من الظهور إلى الإظهار**: تمنحهم المنبر أمام الرعاة والإدارة العليا، فيبنون رصيدهم القيادي.
- **من العلاقات الثنائية إلى فريق القادة**: تبني بين قادتك توجيهًا ومواءمة والتزامًا فيما بينهم، لا ولاءً لك وحدك.

> مقياس قيادة القادة: كم منهم يستطيع أخذ مكانك غدًا.
