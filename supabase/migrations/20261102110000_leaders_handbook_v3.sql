## موقع هذا الإطار وأهدافه
الإطار الثاني جسر بين الأول والثالث: يستلم من المعالم انضباط التنفيذ، ويسلّم للقيادة قيمة مقيسة وأثرًا يمكن التحول به. أهدافه الستة:
1. التعرف على مدارس إدارة المنافع وقياس الأثر العالمية والمقارنة بينها.
2. فهم النموذج الفكري للتقارير القائمة على الأثر بدل تقارير الإنجاز.
3. إتقان سلسلة القيمة الخماسية والتمييز بين الإسناد والمساهمة.
4. إعادة تعريف الأثر بمنظور قيادي: من مؤشر ختامي إلى بوصلة قرار مستمرة.
5. استيعاب مفاهيم المنافع والأثر ونماذجها ومنتجاتها المعرفية.
6. تطبيق قياس الأثر على المشروع والبرنامج والمحفظة.

