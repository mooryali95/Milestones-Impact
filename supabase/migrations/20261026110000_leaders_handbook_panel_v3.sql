### مثال محلول
التحدي: الإدارة القانونية تؤخر مراجعة عقود البرنامج ثلاثة أسابيع في كل دفعة، فتنزلق معالم الترسية.
- **تشخيص**: البيانات تكشف أن معظم التأخير في عقود تصل ناقصة المرفقات، لا في المراجعة نفسها.
- **تأثير**: لقاء مع مدير الإدارة القانونية يبدأ بمصلحته: عبء أقل وعقود أكمل، لا بشكوى من التأخير.
- **حل**: قائمة تحقق مشتركة للمرفقات، ونافذة مراجعة أسبوعية ثابتة، وزمن استجابة متفق عليه.
- **تعاطف**: فريقه مثقل بطلبات جهات كثيرة، فالحل يخفف عنه ولا يضيف إليه.
- **تواصل**: محضر موجز بالاتفاق يصل الطرفين وراعي البرنامج.
- **تتبع**: قراءة زمن المراجعة عند كل معلم ترسية لثلاث دورات، ثم تثبيت الاتفاق أو تعديله.

> الحل الذي يصنعه الطرفان يصمد، والحل المفروض بالتصعيد يعيد المشكلة في الدفعة التالية.
:::

