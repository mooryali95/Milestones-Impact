## سلّم الأدلة
ليس كل دليل أثر بالقوة نفسها، ويُختار مستوى الدليل بحسب حجم القرار المبني عليه:
1. **رواية وشهادات**: تكشف المعنى والتجربة، ولا تثبت التغيير.
2. **قياس قبل وبعد**: يثبت حدوث تغيير، ولا يثبت أننا سببه.
3. **مقارنة بمجموعة لم تستفد**: تقرّب الإسناد إن تشابهت المجموعتان قبل التدخل.
4. **تصميم شبه تجريبي**: كفرق الفروق أو المطابقة، يعزل أثر التدخل إحصائيًا.
5. **تجربة عشوائية محكمة**: أقوى دليل على الإسناد، وأعلاها تكلفة، ولا تصلح لكل تدخل ولا أخلاقيًا في كل سياق.

وحين يتعذر العزل يُستعمل تحليل المساهمة (Contribution Analysis، Mayne): قصة سببية تُختبر خطوة خطوة بالأدلة والتفسيرات البديلة.

> قرار توسيع برنامج على مستوى وطني يحتاج دليلًا من الدرجة الثالثة فأعلى؛ والمراجعة الدورية يكفيها الثاني مع تحليل المساهمة.
