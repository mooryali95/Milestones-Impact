create or replace function leaders._hb_fix(p_dim text, p_chap text, p_old text, p_new text)
returns void language sql as $$
  update leaders.handbook_modules set body_md = replace(body_md, p_old, p_new)
   where dimension = p_dim and chapter_key = p_chap
     and position(p_old in coalesce(body_md, '')) > 0
     and position(p_new in coalesce(body_md, '')) = 0;
$$;

create or replace function leaders._hb_quiz(p_dim text, p_chap text, p_old text, p_new text)
returns void language sql as $$
  update leaders.handbook_modules set quiz_md = replace(quiz_md, p_old, p_new)
   where dimension = p_dim and chapter_key = p_chap
     and position(p_old in coalesce(quiz_md, '')) > 0
     and position(p_new in coalesce(quiz_md, '')) = 0;
$$;

create or replace function leaders._hb_refl(p_dim text, p_chap text, p_old text, p_new text)
returns void language sql as $$
  update leaders.handbook_modules set reflection_ar = p_new
   where dimension = p_dim and chapter_key = p_chap and reflection_ar = p_old;
$$;

