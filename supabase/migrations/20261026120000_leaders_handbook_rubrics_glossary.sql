create or replace function leaders._hb_append(p_dim text, p_chap text, p_mark text, p_text text)
returns void language sql as $$
  update leaders.handbook_modules set body_md = rtrim(body_md) || E'\n\n' || p_text
   where dimension = p_dim and chapter_key = p_chap
     and coalesce(body_md, '') <> ''
     and position(p_mark in body_md) = 0;
$$;

create or replace function leaders._hb_before(p_dim text, p_chap text, p_anchor text, p_mark text, p_text text)
returns void language sql as $$
  update leaders.handbook_modules set body_md = replace(body_md, p_anchor, p_text || E'\n\n' || p_anchor)
   where dimension = p_dim and chapter_key = p_chap
     and position(p_anchor in coalesce(body_md, '')) > 0
     and position(p_mark in coalesce(body_md, '')) = 0;
$$;

