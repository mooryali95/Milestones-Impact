- سجل معالم مرتبط بسجل المخاطر، فكل معلم يراجع مخاطره.
- بوابات مصغرة عند الانتقالات الكبرى: تصميم، بناء، اختبار، تشغيل.
- تقرير معلم من صفحة واحدة.

