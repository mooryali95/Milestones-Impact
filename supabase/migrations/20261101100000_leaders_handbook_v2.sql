## المعلم في السياق التنموي
أربعة أنواع من المعالم تطبق مفهوم نقطة القيادة والتحكم على المشاريع التنموية:
- **معالم تعاقدية مع المانحين**: تقارير المنح، ودفعات التمويل، والمراجعات الدورية.
- **معالم النتائج**: نقاط التحقق من حدوث التغيير لدى المستفيدين، لا مجرد إنجاز الأنشطة.
- **معالم الاستجابة**: في العمل الإغاثي، سرعة الوصول للمستفيد معلم بحد ذاته.
- **معالم الاستدامة**: التحقق من جاهزية المجتمع أو الشريك المحلي لتسلم المشروع.

بهذا تتحول تقارير المانحين من عبء إلى نقاط قيادة.

## المعلم في المشروع الحكومي
للمشروع الحكومي في المملكة معالم لا تظهر في الكتب العالمية، ويخسر القائد الذي يتجاهلها شهورًا:
- **معالم الاعتماد والميزانية**: اعتماد بطاقة المبادرة، وإدراج تكاليفها في الميزانية المعتمدة، وإنهاء الطرح والترسية والتعاقد وفق نظام المنافسات والمشتريات الحكومية. كثير من انزلاق المشاريع الحكومية يبدأ هنا لا في التنفيذ.
- **معالم مؤشرات الجهة المتابعة**: مؤشرات أداء معتمدة في برامج تحقيق رؤية 2030 تُرفع دوريًا، وتُتابع وطنيًا (المركز الوطني لقياس أداء الأجهزة العامة «أداء»). يُصمم معلم قراءة المؤشر من البداية، لا يُجمع له الدليل عند موعد التقرير.
- **معلم التسليم للجهة المشغلة**: المشروع الحكومي ينتهي غالبًا بأصل أو خدمة تتسلمها جهة تشغيل: وزارة أو هيئة أو مشغل من القطاع الخاص. معلم الاستلام التشغيلي يُصمم مع الجهة المشغلة: معايير القبول، ونقل المعرفة، وجاهزية موظفيها، وفترة التشغيل المصاحب.
- **معالم الشراكة مع القطاع الخاص وغير الربحي**: في مشاريع التخصيص والشراكة، وفي منح الجهات المانحة للقطاع غير الربحي، تُربط الدفعات بمعالم أداء موثقة لا بمرور الوقت.

