## الطبقة الثانية: البرنامج
**سؤالها: هل تتحقق المنافع بعد اكتمال المشاريع، ومن يتسلمها؟** لكل منفعة مالك من وحدة الأعمال يتسلمها ويُحاسب عليها، والمنافع تُقاس بعد اكتمال المشاريع لا عنده، وإدارة التبني والتغيير شرط لاستخدام القدرات فعلًا.

**الحوكمة**: مالك تغيير الأعمال (BCM) يقود التبني في وحدات الأعمال ويتسلم المنافع، ومدير البرنامج يقود تحقيق المنافع والاعتماديات، ومجلس البرنامج يملك رؤية المنافع ويقرر عند معالم التكامل. ومالك تغيير الأعمال يقود التبني، ومالك المنفعة يُحاسب عليها؛ وقد يكونان شخصًا واحدًا.

**الأدوات**: ملف لكل منفعة، وسجل المنافع، وخطة تحقيق المنافع بمعالمها.

