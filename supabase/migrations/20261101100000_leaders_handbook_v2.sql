## جدارات القائد في إطار الأثر
**ما يملكه القائد ذاتيًا**:
- التفكير السببي: يرى سلسلة القيمة خلف كل نشاط.
- الأمانة القياسية: يقاوم تجميل الأرقام وادعاء الإسناد.
- سؤال التغيير: يفتتح كل مراجعة بـ"ما الذي تغيّر؟".

**ما يقدمه للمؤسسة**:
- تعيين ملاك المنافع: لا منفعة بلا اسم يُحاسب عليها.
- حوكمة الأدلة: خطوط أساس ومؤشرات تدخل في كل قرار.
- ثقافة التعلم: مراجعات تعترف بما لم يتحقق، وتغذي المحفظة بالدروس.

> كل معلم قيمة اختبار عملي لهذه الجدارات: قراءة الدليل، ومساءلة التغيير، ثم قرار يوجه الاستثمار نحو الأثر.

