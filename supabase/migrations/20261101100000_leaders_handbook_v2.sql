## المحاذاة الاستراتيجية: KPI و OKR
مؤشرات الأداء (KPI) تقيس ما يحدث فعلًا، والأهداف والنتائج المفتاحية (OKR) تحدد ما يجب أن يتغيّر وتُراجع في دورات فصلية. ونضمن الاتساق بثلاث نقاط ربط:
- لا مشروع بلا منفعة، ولا منفعة بلا هدف استراتيجي تخدمه.
- كل منفعة في سجل المنافع تغذي نتيجة مفتاحية.
- مراجعات OKR الفصلية تلتقي بمراجعات المنافع عند المعالم.

@pyramid شجرة المحاذاة
أثر مستهدف: الغاية الاستراتيجية.
