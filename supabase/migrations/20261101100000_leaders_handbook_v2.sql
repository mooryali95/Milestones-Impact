### القيمة المكتسبة (EVM)
تقرأ القيمة المكتسبة الزمن والتكلفة معًا عند كل معلم بثلاثة أرقام: القيمة المخططة (PV) لما كان يجب إنجازه، والقيمة المكتسبة (EV) لما أُنجز فعلًا بسعر الخطة، والتكلفة الفعلية (AC) لما صُرف، وتُقاس كلها إلى الميزانية الكلية عند الإكمال (BAC). ومنها:
- **مؤشر أداء الجدول (SPI = EV ÷ PV)**: أقل من 1 يعني تأخرًا.
- **مؤشر أداء التكلفة (CPI = EV ÷ AC)**: أقل من 1 يعني تجاوزًا.
- **التقدير عند الإكمال (EAC = BAC ÷ CPI)**: التكلفة النهائية المتوقعة إن استمر الأداء كما هو. وإن كان الانحراف عارضًا لا يتكرر فالأدق: EAC = AC + (BAC − EV).

مثال: مشروع ميزانيته 10 ملايين ريال، وعند معلم منتصف المدة كان المخطط 5 ملايين، والمنجز بسعر الخطة 4 ملايين، والمصروف فعلًا 5 ملايين. فمؤشر الجدول 0.8، ومؤشر التكلفة 0.8، والتقدير عند الإكمال 12.5 مليونًا. والقرار عند المعلم ليس تعديل التاريخ، بل اختيار موثق بين إعادة التخطيط، أو تقليص النطاق، أو طلب تمويل إضافي بمبرر محدث.
:::

