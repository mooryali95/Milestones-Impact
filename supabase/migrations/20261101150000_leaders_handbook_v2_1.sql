الأثر ليس فقرة ختامية في التقرير السنوي، بل التغيير المقصود والمقيس الذي يبرر وجود المشروع؛ يُدار من اليوم الأول ولا يُكتشف في النهاية. له خمسة أبعاد:
- **مقصود**: ما التغيير الذي صُمم المشروع لإحداثه عمدًا؟
- **مقيس**: ما المؤشر وخط الأساس اللذان يثبتان حدوثه؟
- **منسوب بأمانة**: ما حدود مساهمتنا فيه: إسناد أم مساهمة؟
- **مملوك**: من مالك المنفعة المسؤول عنها بعد التسليم؟
- **مستدام**: هل يبقى التغيير بعد انتهاء التدخل وتمويله؟

:::min=advanced
وتستلهم هذه الأبعاد الأبعادَ الخمسة لمشروع إدارة الأثر (Impact Management Project، IMP: مبادرة دولية لتوحيد لغة قياس الأثر) ولا تطابقها: ماذا، ولمن، وكم، والمساهمة، والمخاطر.
:::

