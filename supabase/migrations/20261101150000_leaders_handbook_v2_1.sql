## قبل الالتزام وبعده: المبرر وخطة الأدلة
### المبرر والبدائل
قبل أن تُلزم الجهة مواردها، يُسأل سؤالان: لماذا الآن؟ ولماذا هذا الحل دون غيره؟ (مستلهم من حالة العمل في PRINCE2 ونموذج الحالات الخمس لوزارة الخزانة البريطانية):
- **دليل على المشكلة**: مؤشران على الأقل بقيمتهما الحالية ومصدرهما، لا وصف عام.
- **ثلاثة بدائل على الأقل، أولها عدم التدخل**: الوضع الحالي هو خط المقارنة، وبدونه لا يُعرف ما تضيفه المبادرة.
- **مقارنة بالمعايير نفسها**: التكلفة والمنفعة والمخاطر لكل بديل.
- **توصية مسببة**: لماذا يتفوق البديل المختار، وما الذي تتنازل عنه باختياره.

> مبرر يعرض بديلًا واحدًا قرار اتُّخذ ثم بُحث له عن سبب.

### خطة القياس والأدلة
المؤشر يُصمم في سجل المنافع، وخطة الأدلة تجيب كيف سيُقاس فعلًا:
- **لكل مؤشر**: مصدر بياناته، وتكرار قياسه، ومسؤوله، وطريقة التحقق من صحة القياس.
- **خط الأساس قبل التدخل**: تُبنى الخطة قبل التنفيذ لأن ما لم يُقس قبل البدء لا يُستعاد بعده.
- **حماية البيانات الشخصية**: ما يُجمع، ومن يطلع عليه، وكيف يُخفى ما يدل على الأشخاص.
- **المساهمة والإسناد**: كيف تميّز أثر المبادرة من العوامل الأخرى التي تعمل على المستفيدين أنفسهم.

> خطة قياس تُكتب بعد التنفيذ تقيس ما توفر من بيانات، لا ما وعدت به المبادرة.
:::

