## أساسيات الضبط حول المعلم
المعلم لا يُحمى بالنوايا؛ أدوات الضبط التالية تحدد هل تاريخه واقعي، وماذا يحدث حين يتغير شيء:
- **المسار الحرج والفائض الزمني**: المسار الحرج أطول سلسلة أنشطة مترابطة، وأي تأخير فيه يؤخر المعلم ونهاية المشروع مباشرة. والفائض الزمني (Float) ما يحتمله نشاط خارج المسار الحرج من تأخير دون أن يمس المعلم. معلم على المسار الحرج يُتابع أسبوعيًا، ونشاط له فائض يُتابع عند استهلاك فائضه.
- **الاعتماديات**: تُبنى شبكة الجدول من علاقات بين الأنشطة، والاعتمادية الخطأ ترسم مسارًا حرجًا خطأ.
:::min=intermediate
- **أنواع الاعتماديات والإزاحة**: الأنواع أربعة: **انتهاء ← بدء (FS)** لا يبدأ اللاحق حتى ينتهي السابق، وهو الأشيع؛ و**بدء ← بدء (SS)** يبدأ اللاحق بعد بدء السابق دون انتظار انتهائه؛ و**انتهاء ← انتهاء (FF)** لا ينتهي اللاحق قبل انتهاء السابق؛ و**بدء ← انتهاء (SF)** نادر، لا ينتهي اللاحق حتى يبدأ السابق، كتشغيل النظام القديم حتى يبدأ الجديد. و**الإزاحة (Lag)** مدة انتظار تُضاف إلى العلاقة: «يبدأ التدريب بعد ثلاثة أيام من انتهاء التركيب» انتهاء ← بدء بإزاحة 3.
:::
- **ضبط التغيير**: كل تغيير يمس نطاقًا أو موعدًا أو تكلفة معتمدة يمر بطلب تغيير موثق، يُقيّم أثره على خط الأساس والمعالم اللاحقة، ثم يعتمده أو يرفضه صاحب الصلاحية. والإضافة الصامتة إلى النطاق (زحف النطاق) أشهر أسباب انزلاق المعالم.
- **الخطر مقابل المشكلة**: الخطر حدث محتمل لم يقع، يُسجل وتُعد له استجابة: تجنب، أو نقل، أو تخفيف، أو قبول. والمشكلة حدث وقع ويحتاج قرارًا الآن. وحين يقع خطر مسجل تُفعّل خطة استجابته المعدة ويُبلغ صاحب القرار، ولا تُرتجل خطة جديدة.
- **حدود التحمل**: هوامش متفق عليها للانحراف في الزمن والتكلفة؛ ما بقي داخلها يديره مدير المشروع، وما تجاوزها يصعد إلى صاحب القرار. وهذا مبدأ الإدارة بالاستثناء في PRINCE2.

> المعلم الذي لا يرتبط بالمسار الحرج وسجل المخاطر وإجراء التغيير تاريخ يُرجى، لا نقطة تحكم.

:::min=advanced
### القيمة المكتسبة (EVM)
تقرأ القيمة المكتسبة الزمن والتكلفة معًا عند كل معلم بثلاثة أرقام: القيمة المخططة (PV) لما كان يجب إنجازه، والقيمة المكتسبة (EV) لما أُنجز فعلًا بسعر الخطة، والتكلفة الفعلية (AC) لما صُرف، وتُقاس كلها إلى الميزانية الكلية عند الإكمال (BAC). ومنها:
- **مؤشر أداء الجدول (SPI = EV ÷ PV)**: أقل من 1 يعني تأخرًا.
- **مؤشر أداء التكلفة (CPI = EV ÷ AC)**: أقل من 1 يعني تجاوزًا.
- **التقدير عند الإكمال (EAC = BAC ÷ CPI)**: التكلفة النهائية المتوقعة إن استمر الأداء كما هو. وإن كان الانحراف عارضًا لا يتكرر فالأدق: EAC = AC + (BAC − EV).

مثال: مشروع ميزانيته 10 ملايين ريال، وعند معلم منتصف المدة كان المخطط 5 ملايين، والمنجز بسعر الخطة 4 ملايين، والمصروف فعلًا 5 ملايين. فمؤشر الجدول 0.8، ومؤشر التكلفة 0.8، والتقدير عند الإكمال 12.5 مليونًا. والقرار عند المعلم ليس تعديل التاريخ، بل اختيار موثق بين إعادة التخطيط، أو تقليص النطاق، أو طلب تمويل إضافي بمبرر محدث.
:::

## من النطاق إلى الخطة: أدوات وثيقة مبادرتك
هذه الأدوات تبني بها فصول التخطيط في وثيقة مبادرتك، وكل واحدة تأخذ من التي قبلها.

### سجل المخاطر والافتراضات والاعتماديات (RAID)
سجل واحد يجمع أربعة أنواع من البنود، لأنها كلها تهدد المعالم نفسها:
- **خطر**: حدث محتمل لم يقع، له استجابة معدة مسبقًا.
- **افتراض**: أمر نبني عليه الخطة ولم نتحقق منه بعد، كـ«ستعتمد الإدارة المالية الميزانية في الربع الأول». الافتراض الذي يسقط يصير مشكلة.
- **اعتمادية**: عمل يملكه غيرنا ولا نتقدم بدونه، كربط تقني تنفذه جهة أخرى.
- **مشكلة**: حدث وقع ويحتاج قرارًا الآن.

ولكل بند احتمال وشدة أثر من 1 إلى 5، وحاصل ضربهما يرتب الأولوية: 12 فأكثر بند عالٍ لا يُقبل بلا مالك واستجابة محددة وموعد. واربط كل بند برمز حزمة العمل التي يمسها، فيعرف صاحب القرار أي معلم مهدد.

> السجل الذي يُكتب مرة ولا يُراجع في كل اجتماع قرار وثيقة امتثال، لا أداة إدارة.

:::min=intermediate
### هيكل تجزئة العمل (WBS)
يجزئ نطاق المبادرة كله إلى حزم عمل يمكن تقديرها وتسليمها ومحاسبة مالكها:
- **ابدأ بالمخرجات لا بالأنشطة**: المستوى الأول هو المخرجات الرئيسة في بطاقة المبادرة، ثم تُجزأ كل منها إلى حزم.
- **قاعدة 100%**: مجموع الحزم يساوي النطاق كله، لا أكثر ولا أقل. ما ليس في الهيكل ليس في المبادرة، وما في الهيكل خارج النطاق زحف مبكر.
- **ترميز هرمي**: 1، ثم 1.1 و1.2، ثم 2. والرمز هو ما يربط الحزمة بالجدول والتكلفة والسجل والمصفوفة.
- **مالك واحد لكل حزمة**: حزمة بمالكين لا يملكها أحد.
- **قاموس الحزم**: لكل حزمة مهمة معيار اكتمال مكتوب، يجيب عن سؤال واحد: متى نقول إنها انتهت؟

وفي البرنامج يكون المستوى الأول المشاريع المكونة، وفي المحفظة المبادرات.

### تقدير التكلفة من أسفل لأعلى
- **التقدير بالحزمة**: لكل حزمة بنودها بكمية وسعر وحدة، ومجموعها تكلفة الحزمة، ومجموع الحزم تكلفة المبادرة. التقدير من أعلى («نحو مليوني ريال») يصلح للفكرة لا للاعتماد.
- **الاحتياطي من المخاطر**: نسبة تُضاف للمخاطر المعروفة في السجل، ويُبرَّر حجمها منها، ولا تُستعمل إلا بقرار موثق. وهي غير احتياطي الإدارة الذي يحتفظ به الراعي لما لم يُتوقع.
- **المقارنة بالميزانية المتاحة**: التكلفة مع الاحتياطي تُقارن بما هو متاح فعلًا. والفجوة تُعرض على صاحب القرار بخياراتها: تقليص نطاق، أو مراحل، أو تمويل إضافي، ولا تُخفى بخفض التقدير.
- **مصدر التمويل**: من يعتمد الصرف، ومن أي بند، ومتى.

> تقدير بلا حزم لا يُراجع، واحتياطي بلا مخاطر لا يُدافع عنه.
:::

## منتجات العمل المعرفية
- **سجل المعالم**: لكل معلم نوعه وتاريخه ومعايير تحققه وصاحب قراره.
- **تقرير المعلم**: موجز تنفيذي من صفحة واحدة: الحالة، الانحراف، القرار المطلوب.
- **لوحة التحكم**: عرض حي لحالة المعالم عبر المشاريع بالأخضر والأصفر والأحمر.
- **مصفوفة القرارات**: من يقرر ماذا عند أي معلم، فتمنع تعطل القرار وتنازع الصلاحية.
- **نماذج بوابات المراحل**: أسئلة موحدة لكل بوابة تضمن اتساق التقييم.

