### قراءة المقاومة
المقاومة معلومة عن التغيير، لا عيب في الأشخاص. اسأل عن مصدرها قبل أن تتعامل معها:
- **خسارة**: مكانة أو صلاحية أو راحة يفقدها الشخص. تعالج بالاعتراف بها، وتعويض ما يمكن تعويضه.
- **غموض**: لا يعرف ما سيحدث له. يعالج بوضوح مبكر، ولو بما لم يُحسم بعد.
- **كفاءة**: يخشى ألا يتقن الطريقة الجديدة. يعالج بتدريب وفترة تجريب آمنة.
- **ثقة**: تغييرات سابقة وُعد فيها ولم يُوفَ. يعالج بمكسب صغير يُرى قبل الوعد الكبير.

وبعض المقاومة صواب: اعتراض يكشف خللًا في التصميم لم يره الفريق. فاستمع قبل أن تقنع.
:::

:::min=advanced
### كسب المقاومين المؤثرين
المقاوم صاحب النفوذ يحدد موقف من حوله، وكسبه يختصر عليك حملة كاملة:
- **ارسم مصلحته**: ما الذي يحميه بمقاومته؟ والجواب نادرًا ما يكون المبادرة نفسها.
- **أشركه في التصميم**: دور حقيقي في قرار يمسه، لا اجتماع اطلاع.
- **مكسب له مبكرًا**: نتيجة صغيرة تخدم أولوياته هو في الأسابيع الأولى.
- **منبر علني**: حين يتحول، اجعله يروي التغيير بلسانه أمام فريقه.

> المقاوم الذي كسبته أقوى رسول لتغييرك من أي حملة تواصل.
:::

## الملاحظة على الأداء (التغذية الراجعة)
الملاحظة على الأداء أداة تطوير، لا حكم على الشخص. وتُبنى بثلاث خطوات (نموذج SBI من CCL، مركز القيادة الإبداعية: الموقف، والسلوك، والأثر):
1. **الموقف**: متى وأين، بلا تعميم: «في مراجعة البوابة أمس».
2. **السلوك**: ما فعله الشخص كما تلتقطه الكاميرا، لا صفة فيه: «لم يُحدَّث سجل المخاطر منذ ثلاثة أسابيع»، لا «أنت مهمل».
3. **الأثر**: ما ترتب على السلوك: «فدخلنا البوابة بمخاطر قديمة وتأجل القرار».

ثم **حوار** لا خطبة: اسأل عن رؤيته وظروفه، واتفقا على ما يتغير ومتى تعودان إليه.
- **التوقيت**: قريبًا من الموقف، لا مؤجلًا إلى التقييم السنوي.
- **المكان**: على انفراد للتصحيح، وأمام الفريق للتقدير.
- **التوازن**: لاحظ ما يُحسن كما تلاحظ ما يُخطئ، فالتقدير المحدد يكرر السلوك الجيد.

> «أنت لا تهتم» حكم يستدعي الدفاع، ووصف السلوك وأثره يفتح باب الحل.

## التفويض الواضح: مصفوفة RACI
لكل مهمة أو قرار في المشروع أربعة أدوار تُكتب في مصفوفة واحدة:
- **R ينفذ** (Responsible): من يقوم بالعمل، وقد يكون أكثر من شخص.
- **A يقرر** (Accountable): صاحب القرار الذي يُسأل عن النتيجة، وهو **واحد فقط** لكل مهمة.
- **C يُستشار** (Consulted): من يُؤخذ رأيه قبل القرار.
- **I يُبلغ** (Informed): من يُبلغ بعد القرار.

> مهمة بلا A يضيع حسمها، ومهمة لها A مرتين تتنازعها الصلاحية. وقبول المخرج للتشغيل تملكه الجهة المشغلة، لا مدير المشروع.

