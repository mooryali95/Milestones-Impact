وهي مع جدارتي الاستجابة المنضبطة (الباب الثاني) وانتقال العهدة (الباب الثالث) **الجدارات الست** لهذا الإطار، وبها تُبنى خطة التطوير في المختبر.

> التميز في اتجاه واحد أشهر أسباب تعثر قادة المشاريع.

## النماذج العاملة
- **القيادة الموقفية**: أربعة أنماط (توجيه، تدريب، مساندة، تفويض)، والنمط يتبع جاهزية الفرد لا شخصية القائد. أسماء الأنماط من نسخة Blanchard المعروفة بـ SLII، وهي تسمي الجاهزية «مستوى النمو».

@timeline أنماط القيادة الموقفية بحسب الجاهزية
توجيه: كفاءة منخفضة وحماس عالٍ.
تدريب: كفاءة ناشئة وحماس متراجع.
مساندة: كفاءة عالية وثقة متذبذبة.
تفويض: كفاءة وثقة عاليتان.

- **مصفوفة أصحاب المصلحة**: تصنيف بالنفوذ والاهتمام يحدد جرعة التواصل وقناتها (تفصيلها في الباب الخامس وتمرينها في المختبر).
- **إدارة الخلاف (TKI)**: خمسة أنماط بحسب أهمية القضية وأهمية العلاقة (تبسيط لمحوري النموذج الأصليين: الحزم والتعاون):
  - **التعاون** حين تهم القضية والعلاقة معًا ويتسع الوقت لحل يلبي الطرفين.
  - **التسوية** حين يضيق الوقت وتتكافأ الحجج.
  - **التنافس** في قرار عاجل أو مبدئي كالسلامة.
  - **المجاملة** حين تهم العلاقة أكثر من القضية.
  - **التجنب** حين تكون القضية هامشية أو تحتاج النفوس وقتًا لتهدأ.
  وابدأ أي خلاف بتلخيص موقف كل طرف ومصلحته قبل اقتراح الحل.
- **أداة DIRECT للتحديات**: تشخيص، ثم تأثير، ثم حل، يسندها تعاطف وتواصل، ثم تتبع حتى الإغلاق. مسار منضبط للتحديات القيادية اليومية من اجتهاد هذه المنهجية (تفصيلها في الباب السادس للمستوى الاحترافي).

