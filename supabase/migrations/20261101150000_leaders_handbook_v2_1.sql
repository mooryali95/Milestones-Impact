## قاموس المفاهيم الأساسية
- **المنفعة**: تحسن مقيس ناتج عن المخرجات، لها مالك ومؤشر وتاريخ تحقق.
- **النتيجة**: التغيير في السلوك أو الاستخدام الناتج عن تبني المخرجات.
- **خط الأساس**: القياس قبل التدخل؛ لا يمكن إثبات تغيير بلا نقطة انطلاق.
- **مسار القيمة**: تسلسل معالم القيمة من مخرجات إلى أثر، وهو صلة الربط بالإطار الأول.

> كل منفعة نتيجة، وليست كل نتيجة منفعة: المنفعة نتيجة مقيسة مملوكة تخدم هدفًا استراتيجيًا.

## تشريح المؤشر
المؤشر الصالح للقرار جملة كاملة، لا اسم فقط. له سبعة عناصر، وغياب أي منها يجعله شعارًا:
1. **ما يقيسه**: التغيير المقصود بلغة واضحة، لا الجهد المبذول.
2. **الوحدة**: نسبة، أو أيام، أو عدد، أو ريال.
3. **خط الأساس**: القيمة قبل التدخل وتاريخ قياسها.
4. **القيمة المستهدفة**: الرقم الذي نلتزم ببلوغه.
5. **الموعد المستهدف**: متى نبلغه.
6. **المصدر والدورية**: من أين تأتي البيانات، وكل كم تُقرأ.
7. **المالك**: من يُسأل عنه، ويتخذ القرار حين ينحرف.

مثال: «تسريع إصدار السجل التجاري» شعار. ومؤشره الكامل: «متوسط زمن إصدار السجل التجاري بالأيام، من 9 أيام في مارس 2026 إلى 3 أيام بنهاية 2027، من نظام الإصدار شهريًا، ومالكه مدير إدارة السجلات».

- **مؤشر النشاط المتنكر**: «عدد الورش» أو «عدد المنشورات» يقيس جهدنا لا التغيير، ولو سُمي مؤشر وعي أو تمكين.
- **مؤشر للقرار لا للعرض**: يُقرأ عند معالم القيمة، ويدخل في ترتيب الأولويات وتوجيه الاستثمار؛ وما لا يدخل في قرار يُحذف من اللوحة.
- **بيانات الأشخاص**: إن جمع المؤشر بيانات عن أشخاص فاطلب موافقتهم، واجمع أقل ما يخدم القرار، واحمِه وفق نظام حماية البيانات الشخصية.

> المؤشر الذي ينقصه خط أساس لا يثبت تغييرًا، والذي ينقصه موعد لا يُحاسب عليه أحد، والذي ينقصه مالك لا يتحرك حين ينحرف.

## المنافع السلبية والآثار غير المقصودة
- **المنفعة السلبية (Dis-benefit)**: نتيجة يراها صاحب مصلحة واحد على الأقل سلبية، وتنتج عن التغيير نفسه، كتراجع التواصل المباشر بين الموظف والمراجع بعد تحويل خدمة إلى قناة إلكترونية. تُسجل في سجل المنافع بمالك ومؤشر كالمنافع تمامًا، وتُدار لتقليلها، ولا تُخفى. (MSP)
- **الأثر غير المقصود**: تغيير لم يُخطط له، إيجابيًا كان أو سلبيًا، كأن يُقصي التدخل فئة لم يقصدها. يُرصد بسؤال مفتوح في كل مراجعة: ما الذي تغيّر ولم نتوقعه، ومن تأثر به؟ ومعيار الأثر في DAC يشمل المقصود وغير المقصود.
- **الفرق عن الخطر**: الخطر احتمال قد لا يقع، والمنفعة السلبية نتيجة متوقعة من التغيير نفسه حتى لو نجح.

> تقرير أثر بلا منافع سلبية ولا آثار غير مقصودة تقرير ترويجي، لا تقييم.

