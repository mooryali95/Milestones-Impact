## النماذج العاملة
- **إدارة تحقق المنافع (BRM)**: دورة تحديد وتحقيق واستدامة، وسجل منافع حي يُراجع عند كل معلم قيمة.
- **نظرية التغيير (TOC)**: خريطة سببية تكشف الافتراضات الخفية قبل التنفيذ.
- **الإطار المنطقي**: مصفوفة الأهداف والمؤشرات ووسائل التحقق والافتراضات.

:::min=intermediate
- **العائد الاجتماعي على الاستثمار (SROI)**: ترجمة القيمة الاجتماعية والبيئية إلى لغة نقدية مقارنة، ويفرض الصدق بأربعة خصومات: ما كان سيحدث بدوننا (Deadweight)، وما يُنسب لغيرنا (Attribution)، وما أزحناه من مكان آخر (Displacement)، وتناقص الأثر مع الزمن (Drop-off).
:::

