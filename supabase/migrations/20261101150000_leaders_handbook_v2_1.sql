## قيادة القادة
حين يصبح من تقودهم مديري مشاريع وقادة فرق، يتغير عملك من القيادة المباشرة إلى بناء القادة:
- **من الحل إلى السؤال**: تعيد المشكلة إلى صاحبها بسؤال يبني حكمه، ولا تحلها عنه.
- **من متابعة الخطوات إلى المعايير**: تتفق معهم على ما يعنيه «جيد» وحدود التصعيد، ثم تتابع النتائج لا الخطوات.
- **من الظهور إلى الإظهار**: تمنحهم المنبر أمام الرعاة والإدارة العليا، فيبنون رصيدهم القيادي.
- **من العلاقات الثنائية إلى فريق القادة**: تبني بين قادتك توجيهًا ومواءمة والتزامًا فيما بينهم، لا ولاءً لك وحدك.

> مقياس قيادة القادة: كم منهم يستطيع أخذ مكانك غدًا.
:::

## التأثير بلا سلطة
أغلب ما يحتاجه قائد المشروع يملكه غيره: إدارة موازية، أو جهة رقابية، أو مورد. والتأثير هنا لا يأتي من الصلاحية بل من ثلاثة مصادر (Cohen و Bradford):
- **المصلحة المتبادلة**: اربط طلبك بما يهم الطرف الآخر نفسه: عبء يخف عنه، أو هدف يخدمه، أو مخاطرة تُرفع عنه، لا بما يهمك وحدك.
- **الخبرة**: معرفة يحتاجها الطرف الآخر وتقدمها له قبل أن تطلب منه.
- **الثقة والعلاقة**: رصيد من الوفاء بالوعود والعون السابق يُبنى قبل الحاجة إليه.

> التصعيد إلى الإدارة العليا يحسم الخلاف مرة ويخسر العلاقة في كل مرة بعدها؛ يُستعمل حين تفشل المصلحة المتبادلة، لا بدلًا منها.

## قيادة التغيير عند الأفراد
المبادرة تنجح حين يغيّر الناس طريقة عملهم، لا حين تُسلَّم مخرجاتها. ويمر كل فرد متأثر بخمس محطات (نموذج ADKAR من Prosci):
1. **الوعي**: لماذا التغيير، وما كلفة البقاء على الحال؟
2. **الرغبة**: ما الذي يكسبه هو، أو يتجنبه، بالمشاركة؟
3. **المعرفة**: ماذا سيفعل بشكل مختلف، وكيف؟
4. **القدرة**: هل يستطيع فعله في عمله اليومي، بالوقت والأدوات والدعم؟
5. **التعزيز**: ما الذي يمنع عودته إلى الطريقة القديمة؟

قدّر جاهزية كل فئة متأثرة في أي محطة تقف، فالتدخل يتبع المحطة: التدريب لا يعالج غياب الرغبة، والرسائل لا تعالج غياب القدرة.

> تسليم المخرج بلا تعزيز يعني أن المنفعة ستتلاشى بعد مغادرة الفريق.

