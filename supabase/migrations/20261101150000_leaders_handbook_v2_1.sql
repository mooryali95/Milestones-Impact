## قاموس المفاهيم الأساسية
- **الجدارة**: قدرة تظهر في سلوك متكرر يلاحظه الآخرون، تجمع ما تعرفه وما تتقنه وما تميل إليه.
- **النمط القيادي**: طريقة التوجيه والدعم المختارة بحسب جاهزية الفرد.
- **الجاهزية**: قدرة الفرد ورغبته تجاه مهمة محددة، وهي أساس القيادة الموقفية.
- **التفويض**: نقل صلاحية القرار مع بقاء المساءلة؛ لا تخلٍّ ولا وصاية.
- **إدارة الخلاف**: اختيار نمط التعامل مع الخلاف بحسب القضية والعلاقة.
- **الأمان النفسي**: ثقة الفريق بأن رفع المشكلة أو الخطأ لن يُعاقب؛ بدونه لا تصل الأخبار السيئة إلا متأخرة.
- **الأثر القيادي**: ما يبقى في الأشخاص والمؤسسة بعد مغادرة القائد.

> كل نمط سلوك، وليست كل الأنماط جدارة؛ الجدارة اختيار النمط الصحيح للموقف الصحيح.

