-- آمن لإعادة التشغيل. يُشغَّل بعد 20261024200000_leaders_content_bank.
--
-- الشهادة تُبنى مرة (الإعداد العام)، وتُخصَّص بطبقتين لا تتكرر فيهما القيم:
--   • البرنامج: اسمه على الشهادة وساعاته وموقّعه، لكل برنامج يختلف.
--   • الجهة: ما يخصها فوق ذلك، وشعارها بجانب شعار Milestone.
-- ما لا يُخصَّص يُورث من الطبقة التي تحته. التواريخ واسم الدفعة من دفعة
-- المشارك نفسها، كما تحددها رحلته.

alter table leaders.programs add column if not exists cert jsonb not null default '{}'::jsonb;

-- هوية الجهة في تطبيق المشارك: الشعار كبير، فيعرف التطبيق وجوده دون جلبه،
-- ثم يجلبه مرة ويحفظه على الجهاز بحسب updated_at.
alter table leaders.organizations add column if not exists has_logo boolean generated always as (logo is not null) stored;
