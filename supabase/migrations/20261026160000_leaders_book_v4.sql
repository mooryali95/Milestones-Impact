create or replace function leaders._hb_fix(p_dim text, p_chap text, p_old text, p_new text)
returns void language sql as $$
  update leaders.handbook_modules set body_md = replace(body_md, p_old, p_new)
   where dimension = p_dim and chapter_key = p_chap
     and position(p_old in coalesce(body_md, '')) > 0
     and position(p_new in coalesce(body_md, '')) = 0;
$$;

create or replace function leaders._hb_before(p_dim text, p_chap text, p_anchor text, p_mark text, p_text text)
returns void language sql as $$
  update leaders.handbook_modules set body_md = replace(body_md, p_anchor, p_text || E'\n\n' || p_anchor)
   where dimension = p_dim and chapter_key = p_chap
     and position(p_anchor in coalesce(body_md, '')) > 0
     and position(p_mark in coalesce(body_md, '')) = 0;
$$;

create or replace function leaders._hb_quizset(p_dim text, p_chap text, p_md5 text, p_new text)
returns void language sql as $$
  update leaders.handbook_modules set quiz_md = p_new
   where dimension = p_dim and chapter_key = p_chap
     and md5(coalesce(quiz_md, '')) = p_md5;
$$;

