// كانت رسالة واحدة («تعذّر تحميل أداة التحقق») تظهر لكل فشل، فيقرأ من رفضه التحقق أن الأداة لم تُحمَّل
// (تدقيق الإنتاج 2026-11-10). الآن لكل حال رسالتها، ومعها زر لإعادة المحاولة.
export const CAPTCHA_TEXT = {
  // السكربت لم يصل: انقطاع، أو مانع إعلانات، أو شبكة تحجب Cloudflare
  load: 'تعذّر تحميل أداة التحقق. تأكد من اتصالك، أو أوقف مانع الإعلانات لهذه الصفحة، ثم أعد المحاولة.',
  // الأداة حُمّلت ولم يكتمل التحقق (رفض أو خطأ داخلي في الأداة)
  challenge: 'لم يكتمل التحقق. أعد المحاولة، وإن تكرر فجرّب متصفحًا آخر أو ادخل بحساب Google.',
  // انقضت مهلة التفاعل مع الأداة قبل إكمالها
  timeout: 'انتهت مهلة التحقق قبل إكماله. أعد المحاولة.',
};
export const CAPTCHA_RETRY = 'أعد المحاولة';
export const captchaMessage = (kind) => CAPTCHA_TEXT[kind] || CAPTCHA_TEXT.challenge;

// رد الخادم بطلب التحقق (code: captcha). بلا رمز: أول طلب، فتظهر الأداة بلا رسالة. برمز: رفض الخادمُ رمزَ
// الأداة (منتهٍ أو مستعمل)، فتظهر رسالته وتُبنى الأداة من جديد (n يتغير فيعاد تركيبها) بدل أن تبقى مكتملة بلا أثر.
export function captchaGate(r, sentToken) {
  const box = r.site_key ? { site: r.site_key, n: Date.now() } : null;
  return { box, error: !r.site_key || sentToken ? r.message : '' };
}
