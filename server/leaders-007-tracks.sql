-- كل الحقول تُحرَّر من لوحة الإدارة، ولا يكتب هذا الترحيل فوق ما حُرِّر.

create table if not exists leaders.tracks (
  key               text primary key check (key ~ '^M[1-3]I[1-3]L[1-3]$'),
  milestone_level   text not null references leaders.levels(key),
  impact_level      text not null references leaders.levels(key),
  leadership_level  text not null references leaders.levels(key),
  sort              int  not null default 0,
  priority_dimension text references leaders.dimensions(key),   -- محور التركيز الأول في الرحلة
  title_ar          text not null,
  summary_ar        text,      -- لمن صُمّم المسار
  focus_ar          text,      -- أولويات التطوير، كل سطر بند
  project_ar        text,      -- المشروع التطبيقي
  journey_ar        text,      -- كيف تتوجه الرحلة: التدريب والكوتشينغ والأقران، كل سطر بند
  updated_at        timestamptz not null default now(),
  unique (milestone_level, impact_level, leadership_level)
);

