- **مقصود**: ما التغيير الذي صُمم المشروع لإحداثه عمدًا؟
- **مقيس**: ما المؤشر وخط الأساس اللذان يثبتان حدوثه؟
- **منسوب بأمانة**: ما حدود مساهمتنا فيه: إسناد أم مساهمة؟
- **مملوك**: من مالك المنفعة المسؤول عنها بعد التسليم؟
- **مستدام**: هل يبقى التغيير بعد انتهاء التدخل وتمويله؟

> عندما نعيد تعريف الأثر ننتقل من إثبات الإنجاز إلى قيادة التغيير، ونمنع "مسرح الأثر": ادعاءات بلا مؤشر ولا خط أساس.

## قاموس المفاهيم الأساسية
- **المنفعة**: تحسن مقيس ناتج عن المخرجات، لها مالك ومؤشر وتاريخ تحقق.
- **النتيجة**: التغيير في السلوك أو الاستخدام الناتج عن تبني المخرجات.
- **الأثر**: التحول الأوسع طويل المدى الذي تسهم فيه النتائج والمنافع.
- **خط الأساس**: القياس قبل التدخل؛ لا يمكن إثبات تغيير بلا نقطة انطلاق.
- **العائد الاجتماعي**: نسبة القيمة الاجتماعية المولدة إلى الموارد المستثمرة.
- **مسار القيمة**: تسلسل معالم القيمة من مخرجات إلى أثر، وهو صلة الربط بالإطار الأول.

> كل منفعة نتيجة، وليست كل نتيجة منفعة: المنفعة نتيجة مقيسة مملوكة تخدم هدفًا استراتيجيًا.

## تصنيف الأثر
- **مالي واقتصادي**: خفض تكلفة، نمو إيراد، عائد استثمار. الأسهل قياسًا ولغة مجالس الإدارات.
- **تشغيلي ومؤسسي**: سرعة الخدمة، جودة القرار، قدرات جديدة، رضا العاملين. يبني قدرة المؤسسة على أثر أكبر.
- **اجتماعي وتنموي**: تغيير في حياة المستفيدين، تمكين مجتمع، فرص عمل. الأصعب قياسًا والأعمق أثرًا.
- **استراتيجي**: مكانة وسمعة، ثقة الشركاء والمانحين. تراكمي بعيد المدى، يظهر في المحفظة لا في مشروع واحد.

> كل محفظة تحتاج مزيجًا واعيًا من الأنواع الأربعة؛ الاقتصار على الأثر المالي أشهر أخطاء تقارير القيمة.

