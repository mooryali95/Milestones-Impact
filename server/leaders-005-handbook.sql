2. **النتائج المباشرة**: التغيير الأولي في السلوك أو الاستخدام.
3. **المنافع**: التحسن المقيس الذي يعود على المؤسسة أو المستفيد.
4. **التأثير**: التحول الأوسع في المنظومة أو المجتمع.
5. **الأثر المستدام**: التغيير الباقي بعد انتهاء التدخل وتمويله.

> المساءلة تصعد في السلسلة: نسلّم المخرجات، لكن الاستثمار لا يُبرر إلا بالمنافع والأثر المستدام.

## لكل حلقة سؤالها ومقياسها ومالكها
- **المخرجات**: هل سلّمنا ما وعدنا به؟ تُقاس عند الإغلاق بمعايير القبول.
- **النتائج المباشرة**: هل استُخدم المخرج وتغيّر السلوك؟ تُقاس بعد أشهر من التسليم.
- **المنافع**: ما التحسن المقيس مقابل خط الأساس؟ مالكها مالك المنفعة لا مدير المشروع.
- **التأثير**: ما التحول الأوسع الذي أسهمنا فيه؟ بلغة المساهمة لا الإسناد.
- **الأثر المستدام**: هل يبقى التغيير بعد خروجنا؟ يُقاس بعد سنوات وباستقلال عن التدخل.

وتُقرأ السلسلة بحسب القطاع: في التنموي تغيير مقيس في حياة المستفيدين، وفي الخاص منافع مالية وتشغيلية وحصة سوقية، وفي الحكومي أثر على المواطن وجودة الخدمة.

## الإسناد مقابل المساهمة
أشهر فخ في قياس الأثر: متى ننسب التغيير لأنفسنا، ومتى نتحدث عن مساهمة؟
- **الإسناد**: ادعاء أن التغيير حدث بسبب تدخلنا تحديدًا. يتطلب عزل أثر التدخل بخط أساس ومقارنة ومجموعة ضابطة، ويناسب المخرجات والنتائج القريبة.
- **المساهمة**: الإقرار بأن تدخلنا أحد عوامل متعددة صنعت التغيير. تُبنى على سردية سببية موثقة (نظرية التغيير) وأدلة داعمة، وهي اللغة الأمينة لأعلى السلسلة.

> كلما صعدنا في السلسلة ضعف الإسناد وقويت لغة المساهمة، وادعاء الإسناد في أعلى السلسلة يفقد التقرير مصداقيته.

