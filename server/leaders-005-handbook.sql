**أدوات المفاضلة**:
- معايير تقييم موزونة: أثر استراتيجي، عائد، مخاطر، جاهزية.
- التمويل بالأثر: يستمر التمويل ما دامت أدلة القيمة تتراكم.
- مصفوفة التوازن: أثر مالي واجتماعي، قصير وطويل المدى، مؤكد واستكشافي.

