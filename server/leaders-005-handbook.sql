تشهد المؤسسات توسعًا متزايدًا في المشاريع والبرامج والمحافظ وبرامج التحول، لكن هذا التوسع لا ينعكس دائمًا على جودة القرار ولا على تحقيق القيمة والأثر بصورة مترابطة ومستدامة. التحدي لم يعد في إدارة الأنشطة، بل في إدارة العلاقة بين المشاريع والقيمة.

ما توفره القيادة حين تمسك بهذه العلاقة:
- قرارات أفضل مبنية على بيانات وسياق حقيقي.
- رؤية شمولية للأداء والمخاطر والفرص.
- ترابط القيمة بين المشاريع والمنافع والأثر المستهدف.
- وضوح الأولويات ومواءمتها مع الأهداف الاستراتيجية.

## الأطر الثلاثة
تقوم المنهجية على ثلاثة أطر مترابطة تعيد بناء العلاقة بين التنفيذ والأثر والقيادة:
- **الإطار الأول Milestone**: ربط التنفيذ بالأثر عبر نقاط تحكم واضحة وحوكمة فعالة تدعم اتخاذ القرار.
- **الإطار الثاني Impact**: تحقيق القيمة وقياسها عبر سلسلة مترابطة من المخرجات إلى الأثر المستدام.
- **الإطار الثالث Leadership**: تطوير قادة قادرين على التعامل مع التعقيد وقيادة التحول.

> تكامل الأطر الثلاثة يحوّل إدارة المشروعات من متابعة تنفيذية إلى قيادة للأثر والتحول.

## موقع هذا الإطار وأهدافه
الإطار الأول هو الأساس الذي يُبنى عليه الإطاران الثاني والثالث، فلا قياس للأثر ولا قيادة للتحول دون منظومة تحكم منضبطة في التنفيذ. أهدافه الستة:
1. التعرف على نماذج إدارة المشروعات العالمية والمقارنة المنهجية بينها.
2. فهم النموذج الفكري لصناعة القرار من خلال إدارة المشروعات.
3. ضبط العلاقة بين الهيكلة المؤقتة (المشاريع) والهيكلة الدائمة (وحدات الأعمال).
4. إعادة تعريف المعلم بمنظور قيادي: من نقطة زمنية إلى نقطة قيادة وتحكم.
5. استيعاب المفاهيم والنماذج والمنتجات والنظام البيئي المتعلق بالمعلم.
6. تطبيق المفهوم على الطبقات الثلاث: المشروع والبرنامج والمحفظة.

