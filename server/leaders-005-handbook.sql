## الطبقة الثانية: البرنامج
**سؤالها: هل تتكامل المشاريع لتنتج المنافع؟** لكل منفعة مالك من جهة الأعمال يتسلمها ويُحاسب عليها، والمنافع تُقاس بعد اكتمال المشاريع لا عنده، وإدارة التبني والتغيير شرط لاستخدام القدرات فعلًا.

**الحوكمة**: مالك تغيير الأعمال (BCM) يقود التبني في وحدات الأعمال ويتسلم المنافع، ومدير البرنامج يقود تحقيق المنافع والاعتماديات، ومجلس البرنامج يملك رؤية المنافع ويقرر عند معالم التكامل.

**الأدوات**: ملف لكل منفعة (Benefit Profile)، وسجل المنافع (Benefits Register)، وخطة تحقيق المنافع (Benefits Realization Plan) بمعالمها.

**مؤشرات النجاح**: نسبة المنافع المتحققة مقابل المخطط، ونسبة المنافع التي لها مالك ومؤشر وخط أساس، والفجوة الزمنية بين اكتمال المشاريع وأول منفعة.

> البرنامج الذي يكتفي باكتمال مشاريعه جمع مخرجات ولم يصنع منفعة.

