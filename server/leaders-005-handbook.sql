نقرأ المدارس والمعايير العالمية لبناء مستخلص قيادي واعٍ، لا تعصبًا لمدرسة، بل انتقاءً لما يخدم سياق المؤسسة ونضجها. مبدأ "العودة إلى المستخلص" يعني التركيز على المحتوى الأصلي الذي نبعت منه المنهجيات، بعيدًا عن الشعارات التجارية، وبناء قناعة بأن الأدوات وسائل نحو القرار والقيمة لا غاية.

ثلاث فوائد للقائد:
- يتحرر من التعصب لمدرسة واحدة.
- ينتقي ما يناسب سياق مؤسسته.
- يؤسس لغة مشتركة مع الفرق والشركاء والاستشاريين.

## خريطة المدارس والمعايير
- **PMI و PMBOK** (الولايات المتحدة): مجالات المعرفة ومبادئ الأداء وتمكين مدير المشروع.
- **Axelos و PRINCE2** (المملكة المتحدة): الحوكمة والإدارة بالمراحل ومبرر استمرار المشروع.
- **IPMA و ICB** (أوروبا): جدارات الأفراد السلوكية والسياقية والفنية.
- **ISO 21502** (دولي): معيار مرجعي محايد لتوجيه الممارسات.
- **Agile و Hybrid** (عالمي): التسليم التكراري والقيمة المبكرة والتكيف مع التغيير.

> لا توجد مدرسة أفضل بإطلاق؛ توجد مدرسة أنسب لسياق المؤسسة ونضجها ونوع مشاريعها.

## المقارنة المنهجية: PMI مقابل Axelos
- **الفلسفة**: الأمريكية تمكّن مدير المشروع بالمعرفة والأدوات، والبريطانية تضبط المشروع بالحوكمة والمبررات.
- **مركز القرار**: مدير المشروع في الأولى، ومجلس المشروع في الثانية.
- **إدارة المراحل**: دورة حياة مرنة في الأولى، وإدارة بالمراحل مع بوابات إلزامية في الثانية.
- **مبرر الاستمرار**: يُقيّم ضمن دراسات الجدوى في الأولى، ومبدأ ملزم يُراجع عند كل مرحلة في الثانية.
- **الأنسب لـ**: بيئات تحتاج مرونة وعمق أدوات، مقابل بيئات تحتاج حوكمة وضبطًا مؤسسيًا.

> خذ من PMI عمق الأدوات وتمكين المدير، وخذ من Axelos صرامة الحوكمة ونقاط القرار. هذا جوهر نموذج المعلم.

