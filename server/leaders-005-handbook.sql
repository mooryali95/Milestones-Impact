- **النجاح**: من الالتزام بالخطة إلى تعظيم القيمة.
- **المتابعة**: من رد الفعل إلى الفعل القيادي الاستباقي.

## حلقة صناعة القرار
دورة من خمس مراحل يديرها القائد، وتعود نهايتها إلى بدايتها:
1. **معلومة موثوقة**: بيانات أداء حقيقية من الميدان، لا انطباعات.
2. **نقطة تحكم**: لحظة مجدولة ومحوكمة لمراجعة الموقف، وهي المعلم.
3. **قرار**: استمرار أو تصحيح أو تصعيد أو إيقاف، بوضوح وصلاحية.
4. **قيمة**: أثر القرار على المنافع والأهداف.
5. **تعلم**: توثيق الدروس وتغذية القرارات القادمة.

> المعلم هو البنية التحتية لهذه الحلقة؛ بدونه تصبح القرارات عشوائية التوقيت ومبنية على معلومات متقادمة.

## الهيكلة المؤقتة مقابل الهيكلة الدائمة
المشاريع هيكلة مؤقتة لها بداية ونهاية، ووحدات الأعمال هيكلة دائمة. ويظهر الاحتكاك بينهما في:
- تنازع الموارد بين التشغيل والمشاريع.
- ازدواجية التبعية لأعضاء الفرق.
- غموض الصلاحيات بين مدير المشروع والمدير الوظيفي.

ويُدار هذا التوتر بـ:
- حوكمة واضحة تحدد صلاحيات كل طرف عند كل معلم.
- ميثاق المشروع عقدًا داخليًا ملزمًا.
- نقاط تسليم وتسلم بين المشروع ووحدة الأعمال عند الإغلاق.
- رعاية تنفيذية تحسم النزاعات بسرعة.

