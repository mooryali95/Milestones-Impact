- تعيين ملاك المنافع: لا منفعة بلا اسم يُحاسب عليها.
- حوكمة الأدلة: خطوط أساس ومؤشرات تدخل في كل قرار.
- بناء الأثر: نتائج مستدامة وقيمة مضافة للمؤسسة.

