## الطبقة الثانية: البرنامج
**سؤالها: هل تتكامل المشاريع لتنتج المنافع؟** البرنامج مجموعة مشاريع مترابطة تُدار بتنسيق لتحقيق منافع لا تتحقق بإدارتها منفردة. ومعلم البرنامج نقطة التقاء المشاريع لتحقيق قيمة أكبر من مجموع الأجزاء.

**الحوكمة**: مدراء المشاريع يسلمون مخرجات تتكامل عند معالم البرنامج، ومدير البرنامج يدير الاعتماديات والموارد المشتركة، ومجلس البرنامج يملك رؤية المنافع ويقرر عند معالم التكامل.

**خريطة المنافع**: مخرجات المشاريع، ثم قدرات جديدة، ثم منافع، ثم أهداف استراتيجية. لكل منفعة مالك ومؤشر وتاريخ تحقق متوقع، وهذا التاريخ معلم برنامج. والمشروع الذي لا يغذي أي منفعة مرشح للإيقاف.

**فخاخ يجب تجنبها**: إدارة البرنامج كمشاريع متجاورة بلا معالم تكامل، ومنافع بلا مالك، وإعلان النجاح قبل التحقق من المنافع، وإهمال إدارة التغيير، ونسخ معالم المشاريع بدل تصميم نقاط التقاء.

## الطبقة الثالثة: المحفظة
