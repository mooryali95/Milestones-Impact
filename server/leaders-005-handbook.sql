- **أصحاب المصلحة**: منظومة معقدة من مستفيدين ومانحين وحكومات وشركاء محليين ومجتمعات.
- **التمويل**: مرتبط بمتطلبات المانحين وتقاريرهم ودورات المنح.
- **القياس**: التغيير في حياة الناس أصعب قياسًا من الربح والخسارة.
- **السياق**: بيئات متغيرة وأحيانًا هشة، من الاستجابة الإغاثية إلى التنمية المجتمعية.

مجالاتها الرئيسية ثلاثة: البرامج الإغاثية (استجابة سريعة وتأثير ملموس)، والتعليمية (بناء معرفة وتنمية بشرية)، والاجتماعية (تمكين مجتمعي وتنمية مستدامة).

## الإدارة القائمة على النتائج (RBM)
المنهجية المعتمدة لدى المنظمات الدولية والأممية، وتقوم على سلسلة النتائج:
1. **المدخلات**: الموارد المالية والبشرية والمعرفية.
2. **الأنشطة**: ما ننفذه من أعمال وتدخلات.
3. **المخرجات**: ما ننتجه مباشرة من الأنشطة.
4. **النتائج**: التغيير الذي يحدث لدى المستفيدين.
5. **الأثر**: التحول طويل المدى في المجتمع.

> المساءلة تصعد في السلسلة: ننفذ الأنشطة، لكننا نُحاسب على النتائج والأثر.

## الإطار المنطقي ونظرية التغيير
أداتان مترابطتان لكن مختلفتان، وهما لغة المانحين والمنظمات الدولية:
- **الإطار المنطقي**: مصفوفة تربط الأهداف بالمؤشرات ووسائل التحقق والافتراضات، وتجيب: ماذا نريد أن نحقق؟ كيف نقيسه؟ ما الذي نفترضه؟
- **نظرية التغيير**: خريطة سببية تشرح لماذا نعتقد أن هذه التدخلات ستحدث هذا التغيير، وتكشف الافتراضات الخفية قبل التنفيذ.

> نظرية التغيير هي "لماذا وكيف"، والإطار المنطقي هو "ماذا وبأي مؤشر".

## المعلم في السياق التنموي
