إدارة المشروعات ليست علم تنفيذ الخطط، بل نموذج فكري لصناعة القرار في بيئة مؤقتة ومعقدة ومحدودة الموارد. التحول الذهني المطلوب:
- **السؤال**: من "هل أنجزنا المهام؟" إلى "ما القرار المطلوب الآن؟".
