المعلم ليس مجرد تاريخ على الجدول الزمني، بل نقطة قرار محورية نقيس من خلالها التقدم، ونتحكم بالمخاطر، ونؤكد تحقيق القيمة. له خمسة أبعاد يسأل عنها القائد:
- **قرار**: ما القرار الذي سيُتخذ عند هذه النقطة؟
- **توقيت**: متى تقع في مسار المشروع، ولماذا هناك تحديدًا؟
- **تحكم**: ما الذي نضبطه عندها: النطاق أم الجودة أم المخاطر أم الموارد؟
- **قياس**: ما المؤشرات التي تُقرأ عندها؟
- **قيمة**: ما القيمة التي نتحقق من اقترابها أو تحققها؟

> عندما نعيد تعريف المعلم ننتقل من إدارة الزمن إلى قيادة القيمة.

## قاموس المفاهيم الأساسية
- **المعلم**: نقطة قيادة وتحكم تمثل إنجازًا محوريًا أو حدثًا مفصليًا، ومدتها صفر.
- **نقطة التحكم**: لحظة محوكمة لمراجعة الأداء واتخاذ القرار.
- **بوابة المرحلة**: معلم إلزامي لا يُعبر إلا بقرار رسمي: استمرار أو تصحيح أو إيقاف.
- **خط الأساس**: النسخة المعتمدة من الخطة التي يُقاس الانحراف عنها.
- **مبرر الاستمرار**: السؤال الدائم: هل ما زال المشروع يستحق الاستثمار؟
- **مسار القيمة**: تسلسل المعالم التي تنقل المشروع من مخرجات إلى أثر.

> كل بوابة مرحلة معلم، وليس كل معلم بوابة مرحلة: البوابة قرار إلزامي، والمعلم قد يكون نقطة قياس وتحقق.

## أنواع المعالم الأربعة
- **تعاقدية**: توقيع العقد، تسليم دفعة، انتهاء الضمان، تقرير مانح. تحمي الالتزامات المالية والقانونية.
- **تقنية أو إنجاز**: اكتمال التصميم، إطلاق النسخة التجريبية، اجتياز الاختبارات. تؤكد النضج الفني قبل البناء عليه.
- **حوكمية أو قرار**: بوابة اعتماد الجدوى، قرار الانتقال بين المراحل، مراجعة المحفظة. تضمن أن الاستمرار قرار واعٍ لا قصور ذاتي.
- **قيمة أو منافع**: أول مستفيد يستخدم الخدمة، تحقق أول منفعة مقيسة، بلوغ مؤشر أثر. تحوّل النقاش من "هل أنجزنا؟" إلى "ماذا تغيّر؟".

> كل مشروع يحتاج مزيجًا من الأنواع الأربعة؛ الاقتصار على المعالم التقنية أشهر أخطاء الجدولة.

## النماذج العاملة
- **بوابات المراحل**: تقسيم المشروع إلى مراحل تفصلها بوابات قرار إلزامية، ومراجعة المبرر والمخاطر والجاهزية عند كل بوابة.
- **الإدارة بالمراحل (PRINCE2)**: تفويض الصلاحية مرحلة بمرحلة، فلا يُعتمد المشروع كله دفعة واحدة.
- **جدولة المعالم (PMI)**: بناء الجدول من المعالم الكبرى نزولًا إلى التفاصيل، لا العكس.

