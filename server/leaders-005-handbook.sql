## حلقة قيادة الأثر
دورة متكاملة لإدارة المنافع من خمس مراحل:
1. **تعريف المنافع**: خريطة منافع، ولكل منفعة مؤشر وخط أساس ومالك.
2. **قياس عند المعلم**: قراءة مؤشرات القيمة عند معالم القيمة (الإطار الأول).
3. **قرار**: تعزيز أو تصحيح مسار أو إعادة توجيه الاستثمار بناءً على الأدلة.
4. **تحقق وتوثيق**: توثيق المنفعة المتحققة وربطها بالهدف الاستراتيجي.
5. **استدامة وتعلم**: تسليم المنفعة لمالكها التشغيلي وتغذية المحفظة بالدروس.

> كل منفعة بلا مالك ومؤشر وخط أساس وعد إنشائي، لا التزام قابل للقياس والمساءلة.

